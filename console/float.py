"""
FLOAT (float)
Números que contienen decimales.
"""

precio = 19.99
altura = 1.75
temperatura = -2.5

print(precio)
print(altura)
print(temperatura)

# Operaciones
a = 10.5
b = 2.0

print(a + b)
print(a - b)
print(a * b)
print(a / b)

# Convertir un entero a float
numero = 10
numero_decimal = float(numero)

print(numero_decimal)
print(type(numero_decimal))

